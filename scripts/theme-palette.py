# Generates src/theme/palette.css (colour scales for light and night mode).
# Run: python3 scripts/theme-palette.py > src/theme/palette.css
import sys
STEPS=[50,100,200,300,400,500,600,700,800,900,950]
def hx(h): h=h.lstrip('#'); return tuple(int(h[i:i+2],16) for i in (0,2,4))
def mix(a,b,t): a,b=hx(a),hx(b); return '#%02x%02x%02x'%tuple(round(a[i]*(1-t)+b[i]*t) for i in range(3))
def rgba(h,a): r,g,b=hx(h); return f'rgb({r} {g} {b} / {a})'
FAM={
 'accent':  ['#f2f7fe','#e3edfd','#c5d9fb','#97bcf6','#5a95ee','#2f73e0','#005bd3','#004bb0','#003d8f','#002f6e','#001f4a'],
 'magic':   ['#f8f5ff','#efe8ff','#ddd0ff','#c3abff','#a07cff','#8051ff','#6e3ae6','#5a2ec0','#47249a','#351b73','#23114d'],
 'info':    ['#eef9fd','#d8f1fa','#b0e2f4','#7ccbe9','#3fb0da','#1694c2','#0b7aa3','#0a6283','#0b4f69','#0c3f53','#072835'],
 'success': ['#effaf4','#d9f3e4','#b3e6c9','#7fd1a5','#45b47d','#2a9d65','#29845a','#1f6b48','#175538','#0f3f2a','#08281a'],
 'warning': ['#fff8ec','#ffefd2','#ffdfa6','#ffc96b','#f5ad2e','#e8960e','#b97500','#8a5900','#6b4500','#4f3300','#3a2800'],
 'critical':['#fff4f3','#fee5e3','#fdcbc6','#fba398','#f6705f','#ef4d2f','#d0301a','#b02510','#8e1f0b','#6f1a0b','#440f05'],
}
NEUTRAL_L=['#f7f7f7','#f1f1f1','#e3e3e3','#cccccc','#767676','#616161','#4a4a4a','#383838','#2a2a2a','#1a1a1a','#0d0d0d']
NEUTRAL_ISLAND=['#f7f7f7','#f1f1f1','#e3e3e3','#cccccc','#a3a3a3','#8c8c8c','#616161','#383838','#2a2a2a','#1a1a1a','#0d0d0d']
NEUTRAL_D=['#262626','#141414','#333333','#454545','#8a8a8a','#a3a3a3','#bdbdbd','#d4d4d4','#e6e6e6','#f2f2f2','#fafafa']
MAP={'slate':'neutral','gray':'neutral','zinc':'neutral','neutral':'neutral','stone':'neutral',
 'blue':'accent','indigo':'accent','violet':'accent',
 'purple':'magic','fuchsia':'magic','pink':'magic',
 'sky':'info','cyan':'info',
 'emerald':'success','green':'success','teal':'success','lime':'success',
 'amber':'warning','orange':'warning','yellow':'warning',
 'red':'critical','rose':'critical'}
def dark(f):
    L=FAM[f]; base=L[5]
    tints=[rgba(base,.12),rgba(base,.18),rgba(base,.32),rgba(base,.5)]
    ts=[.1,.22,.34,.46,.6,.72,.84]
    return tints+[mix(L[4],'#ffffff',t) for t in ts]
out=['/* Generated by scripts/theme-palette.py. Edit the script, not this file. */']
w=out.append
# scale vars
def scale_block(sel,getter):
    w(sel+' {')
    for name,fam in MAP.items():
        vals=getter(fam)
        w('  '+' '.join(f'--color-{name}-{s}: {v};' for s,v in zip(STEPS,vals)))
    w('}')
scale_block(':root', lambda f: NEUTRAL_L if f=='neutral' else FAM[f])
scale_block('html.dark', lambda f: NEUTRAL_D if f=='neutral' else dark(f))
# dark islands: neutral 700-950 backgrounds keep the light palette for their content
isl=[]
for n in ['slate','gray','zinc','neutral','stone']:
    for s in [700,800,900,950]:
        isl.append(f'[class~="bg-{n}-{s}"]'); isl.append(f'[class*=" bg-{n}-{s}/"]'); isl.append(f'[class^="bg-{n}-{s}/"]')
for n,f in MAP.items():
    if f=='neutral': continue
    for st in [500,600,700,800,900,950]:
        isl.append(f'[class~="bg-{n}-{st}"]'); isl.append(f'[class*=" bg-{n}-{st}/"]'); isl.append(f'[class^="bg-{n}-{st}/"]')
for x in ['bg-black']:
    isl += [f'[class~="{x}"]', f'[class*=" {x}/"]', f'[class^="{x}/"]']
w('/* Dark islands (camera view, player, toasts, solid coloured buttons and badges) keep the light-theme scale so their light text stays light. */')
w(':is('+',\n  '.join(isl)+') {')
for n,f in MAP.items():
    vals=NEUTRAL_ISLAND if f=='neutral' else FAM[f]
    w('  '+' '.join(f'--color-{n}-{s}: {v};' for s,v in zip(STEPS,vals)))
w('}')
WHITE = ':is(.bg-white, [class*=" bg-white/"], [class^="bg-white/"])'
w('/* A white card inside a dark island (login box) switches back to the normal scale. */')
scale_block(WHITE, lambda f: NEUTRAL_L if f=='neutral' else FAM[f])
scale_block('html.dark '+WHITE, lambda f: NEUTRAL_D if f=='neutral' else dark(f))
w('/* Night mode: white surfaces take the card colour through --color-white, so hover utilities keep working. */')
w('html.dark '+WHITE+' { --color-white: var(--ui-surface); }')
def fill(cls):
    return [f'[class~="{cls}"]', f'[class*=" {cls}/"]', f'[class^="{cls}/"]']
keep=[]
for n,f in MAP.items():
    for st in ([600,700,800,900,950] if f=='neutral' else [400,500,600,700,800,900,950]):
        keep += fill(f'bg-{n}-{st}')
keep += fill('bg-black') + ['[class*="bg-gradient-"][class*="text-white"]', '[class*=" bg-["]', '[class^="bg-["]', '[style*="background"]']
w('/* ...but white text on coloured or dark fills stays white. */')
w('html.dark :is('+',\n  '.join(keep)+') { --color-white: #ffffff; }')
w('html.dark :is('+','.join(f'[class~="bg-{n}-{s}"]' for n in ['slate','gray'] for s in [700,800,900,950])+') { background-color: var(--ui-island); }')
sys.stdout.write('\n'.join(out)+'\n')
